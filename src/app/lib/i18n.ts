export type TranslationKey = keyof typeof text.en;

export function t(language: Language, key: TranslationKey) {
  return text[language][key] || text.en[key];
}

const activityKeys: Record<string, TranslationKey> = {
  All: "all",
  Hiking: "hiking",
  "Trail Running": "trailRunning",
  Jogging: "jogging",
  Cycling: "cycling",
  Swimming: "swimming",
  Diving: "diving",
  "Rock Climbing": "rockClimbing",
  "Water Sports": "waterSports",
  Camping: "camping",
  "Family Friendly": "familyFriendly",
  Beginner: "beginner",
  Advanced: "advanced",
  "Pet Friendly": "petFriendly",
};

export function activityLabel(language: Language, label: string) {
  const key = activityKeys[label];
  return key ? t(language, key) : label;
}

export function difficultyLabel(language: Language, label: string) {
  if (label === "Easy") return language === "ms" ? "Mudah" : language === "zh" ? "简单" : "Easy";
  if (label === "Moderate") return language === "ms" ? "Sederhana" : language === "zh" ? "中等" : "Moderate";
  if (label === "Hard") return language === "ms" ? "Sukar" : language === "zh" ? "困难" : "Hard";
  return label === "All" ? t(language, "all") : label;
}

export function budgetLabel(language: Language, label: string) {
  if (label === "Free") return language === "ms" ? "Percuma" : language === "zh" ? "免费" : "Free";
  if (label === "Low") return language === "ms" ? "Rendah" : language === "zh" ? "低" : "Low";
  if (label === "Medium") return language === "ms" ? "Sederhana" : language === "zh" ? "中等" : "Medium";
  if (label === "High") return language === "ms" ? "Tinggi" : language === "zh" ? "高" : "High";
  return label === "All" ? t(language, "all") : label;
}
